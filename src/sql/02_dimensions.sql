-- Dimension: dim_date, dim_customer, dim_product, dim_seller, dim_geography, dim_payment_type, dim_order_status.

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key                    INTEGER PRIMARY KEY,
    full_date                   DATE UNIQUE,
    "day"                       SMALLINT,
    "month"                     SMALLINT,
    month_name                  TEXT,
    "quarter"                   SMALLINT,
    "year"                      SMALLINT,
    year_month                  CHAR(7),
    day_of_week                 SMALLINT,
    day_name                    TEXT,
    is_weekend                  BOOLEAN,
    is_holiday                  BOOLEAN,
    holiday_name                TEXT,
    is_black_friday             BOOLEAN
);

CREATE TABLE IF NOT EXISTS dw.dim_geography (
    geography_key               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zip_code_prefix             CHAR(5) UNIQUE,
    city                        TEXT,
    state_code                  CHAR(2),
    state_name                  TEXT,
    region                      TEXT,
    latitude                    NUMERIC(9,6),
    longitude                   NUMERIC(9,6),
    has_coordinates             BOOLEAN
);

CREATE TABLE IF NOT EXISTS dw.dim_customer (
    customer_key                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_unique_id          CHAR(32),
    geography_key               INTEGER NOT NULL REFERENCES dw.dim_geography(geography_key),
    valid_from                  TIMESTAMP,
    valid_to                    TIMESTAMP,
    is_current                  BOOLEAN,
    "version"                   SMALLINT,
    UNIQUE(customer_unique_id, "version")
);

CREATE TABLE IF NOT EXISTS dw.dim_seller (
    seller_key                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id                   CHAR(32) UNIQUE,
    geography_key               INTEGER NOT NULL REFERENCES dw.dim_geography(geography_key)
);

CREATE TABLE IF NOT EXISTS dw.dim_product (
    product_key                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id                  CHAR(32) UNIQUE,
    category_name               TEXT,
    category_name_en            TEXT,
    name_length                 INTEGER,
    description_length          INTEGER,
    photos_qty                  INTEGER,
    weight_g                    NUMERIC(10,2),
    length_cm                   NUMERIC(10,2),
    height_cm                   NUMERIC(10,2),
    width_cm                    NUMERIC(10,2)
);

CREATE TABLE IF NOT EXISTS dw.dim_order_status (
    order_status_key            SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_status                TEXT UNIQUE
);

CREATE TABLE IF NOT EXISTS dw.dim_payment_type (
    payment_type_key          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_type              TEXT UNIQUE
);


